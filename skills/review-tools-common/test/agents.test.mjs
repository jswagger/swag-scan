import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { buildAgents } from '../../../scripts/build-agents.mjs';
import { evaluateCommand } from '../../../hooks/guard-bash.mjs';
import { AGENTS } from '../swag-scan.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const KNOWN_TOOLS = ['Read', 'Grep', 'Glob', 'Bash', 'Edit', 'Write'];
const IGNORED_FOR_PLUGINS = ['permissionMode', 'hooks', 'mcpServers', 'initialPrompt'];

function parse(content) {
  const [, header, body] = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(content);
  const fields = Object.fromEntries(header.split('\n').map((line) => {
    const index = line.indexOf(':');
    return [line.slice(0, index), line.slice(index + 1).trim()];
  }));
  const list = (value = '') => value.split(',').map((entry) => entry.trim()).filter(Boolean);
  return { fields, tools: list(fields.tools), disallowed: list(fields.disallowedTools), body };
}

const agents = buildAgents().map((entry, index) => ({ ...entry, agent: AGENTS[index], ...parse(entry.content) }));

test('the committed agent files match what the generator produces', () => {
  for (const { path, content } of agents) {
    assert(existsSync(join(ROOT, path)), `${path} is missing. Run: node scripts/build-agents.mjs`);
    assert.equal(readFileSync(join(ROOT, path), 'utf8'), content, `${path} is out of date. Run: node scripts/build-agents.mjs`);
  }
  assert.equal(spawnSync(process.execPath, [join(ROOT, 'scripts', 'build-agents.mjs'), '--check'], { encoding: 'utf8' }).status, 0);
});

test('there is one agent per crew member, named as the crew, with a routing description', () => {
  assert.deepEqual(agents.map(({ fields }) => fields.name), ['analyst', 'inspector', 'security-guard']);
  for (const { fields, agent } of agents) {
    assert.match(fields.description, new RegExp(`Swag Scan ${agent.name}`));
    assert(fields.description.length < 400);
  }
});

test('frontmatter uses only fields that plugin agents honor', () => {
  for (const { fields, path } of agents) {
    for (const ignored of IGNORED_FOR_PLUGINS) assert.equal(ignored in fields, false, `${path} sets ${ignored}, which plugin agents ignore`);
    assert.match(fields.model, /^(sonnet|opus|haiku|inherit)$/);
    assert(Number(fields.maxTurns) > 0);
  }
});

test('tool limits: nobody can create files, only the Inspector can edit, and the Security Guard is report-only', () => {
  const by = Object.fromEntries(agents.map((entry) => [entry.agent.id, entry]));
  for (const entry of agents) {
    for (const tool of [...entry.tools, ...entry.disallowed]) assert(KNOWN_TOOLS.includes(tool), `unknown tool ${tool}`);
    assert(entry.tools.includes('Bash') && entry.tools.includes('Read'));
    assert(!entry.tools.includes('Write'), `${entry.path} must not allow Write`);
    assert(entry.disallowed.includes('Write'));
  }
  assert(by.inspector.tools.includes('Edit'));
  assert(!by.inspector.disallowed.includes('Edit'));
  for (const id of ['analyst', 'security-guard']) {
    assert(!by[id].tools.includes('Edit'));
    assert(by[id].disallowed.includes('Edit'));
  }
});

test('every agent carries its persona, the shared voice rules, and its own tool belt', () => {
  for (const { body, agent, path } of agents) {
    assert.match(body, new RegExp(`You are the ${agent.name}\\b[^.]*Swag Scan crew`), path);
    assert.match(body, /Wording only\./, `${path} is missing the voice rules`);
    assert.match(body, /Serious findings stay plain/);
    assert(body.includes(`\${CLAUDE_PLUGIN_ROOT}/skills/${agent.tool}/SKILL.md`), path);
    assert(existsSync(join(ROOT, 'skills', agent.tool, 'SKILL.md')));
    assert(body.includes(`id: "${agent.id}"`));
    assert.match(body, /Never put an unchecked file under Clean/);
    assert.match(body, /You never ask the user questions/);
    assert.match(body, /Never push, delete branches or files/);
    assert.match(body, /Generated by scripts\/build-agents\.mjs/);
  }
});

test('the agents do not mention each other\'s tools as their own belt', () => {
  const security = agents.find(({ agent }) => agent.id === 'security-guard').body;
  assert.match(security, /report-only/i);
  assert.doesNotMatch(security, /skills\/bug-hunter\/SKILL\.md/);
});

test('every command an agent is told to run is allowed by the Bash guard, and agents save their findings', () => {
  for (const { body, agent, path } of agents) {
    const commands = [...body.matchAll(/`(node \$\{CLAUDE_PLUGIN_ROOT\}[^`]+)`/g)].map((match) => match[1].replaceAll('${CLAUDE_PLUGIN_ROOT}', ROOT));
    assert(commands.length > 0, `${path} names no commands`);
    for (const command of commands) {
      assert.equal(evaluateCommand(command, { cwd: '/work/repo', pluginRoot: ROOT }).allow, true, `${path}: the guard would block: ${command}`);
    }
    assert(body.includes(`save-findings.mjs --agent ${agent.id}`), `${path} does not tell the agent to save its findings`);
    assert.match(body, /Save your findings in the shared format/);
  }
  const by = Object.fromEntries(agents.map((entry) => [entry.agent.id, entry.body]));
  assert.match(by.analyst, /--format bug-hunter/);
  assert.match(by.inspector, /`auto-fixed`/);
  assert.match(by['security-guard'], /Every disposition is `needs-decision` because you are report-only/);
});

test('the heredoc that saves findings is allowed by the guard', () => {
  const command = ['cat > .swag-scan/run/findings-input.json <<\'EOF\'', '{"findings": []}', 'EOF',
    `node ${ROOT}/skills/review-tools-common/save-findings.mjs --agent inspector --input .swag-scan/run/findings-input.json`].join('\n');
  assert.equal(evaluateCommand(command, { cwd: '/work/repo', pluginRoot: ROOT }).allow, true);
});
